defmodule Md.Listener.Sanitizer do
  @moduledoc """
  A listener that strips unsafe markup from the AST as it is built.

  `Md` already filters inline attributes (`:attribute_allowlist`) and refuses
  executable URI schemes, but a syntax definition is free to emit any tag and
  any attribute a custom transform likes. This listener is the second line of
  defence: it is applied to the *result* of parsing, so it catches whatever a
  custom syntax or transform produced.

  Two things are removed:

    * elements whose name is not in `:allowed_tags` (defaults to the HTML
      elements a markup renderer plausibly emits);
    * attributes that are event handlers (`on*`), that carry an executable URI
      scheme, or that are not in `:allowed_attributes`.

  Removed elements keep their *content* -- a `<script>` disappears, but the
  text around it survives -- so sanitising never silently eats a document.

  ## Usage

      Md.parse(input, %Md.Parser.State{listener: Md.Listener.Sanitizer})

  Or, to sanitise an AST produced elsewhere:

      Md.Listener.Sanitizer.sanitize(ast)

  ## Options

  Pass a map as the listener to override the defaults:

      %Md.Parser.State{
        listener: {Md.Listener.Sanitizer, %{allowed_tags: [:p, :b, :i]}}
      }
  """

  use Md.Listener, emoji: "🧼"

  alias Md.Attributes
  alias Md.Parser.State

  @allowed_tags ~w|
    a abbr article aside b blockquote br caption center cite code col colgroup dd
    del details div dl dt em figcaption figure h1 h2 h3 h4 h5 h6 hr i iframe img
    ins kbd li mark ol p pre q s samp section small span strike strong sub summary
    sup table tbody td tfoot th thead tr u ul var
  |a

  @doc "Tags kept by default"
  @spec allowed_tags() :: [atom()]
  def allowed_tags, do: @allowed_tags

  @doc """
  Sanitises an AST, returning a new one.

  `options` accepts `:allowed_tags` and `:allowed_attributes`.
  """
  @spec sanitize(Md.Listener.branch(), map()) :: Md.Listener.branch()
  def sanitize(ast, options \\ %{}) do
    allowed_tags = Map.get(options, :allowed_tags, @allowed_tags)
    allowed_attributes = Map.get(options, :allowed_attributes)

    ast
    |> List.wrap()
    |> Enum.flat_map(&sanitize_node(&1, allowed_tags, allowed_attributes))
  end

  @spec sanitize_node(Md.Listener.branch(), [atom()], nil | [atom()]) :: [Md.Listener.branch()]
  defp sanitize_node(node, _tags, _attrs) when is_binary(node), do: [node]

  defp sanitize_node({tag, attrs, content}, tags, allowed_attributes)
       when is_atom(tag) do
    content = sanitize(content, %{allowed_tags: tags, allowed_attributes: allowed_attributes})

    # An unknown element is unwrapped rather than deleted: its children are
    # still the author's text.
    if tag in tags,
      do: [{tag, sanitize_attrs(attrs, allowed_attributes), content}],
      else: content
  end

  defp sanitize_node(other, _tags, _attrs), do: [other]

  @spec sanitize_attrs(nil | map(), nil | [atom()]) :: nil | map()
  defp sanitize_attrs(attrs, allowed_attributes) when is_map(attrs) do
    attrs
    |> Enum.reject(fn {key, value} ->
      not safe_attribute?(key, value, allowed_attributes)
    end)
    |> Map.new()
  end

  defp sanitize_attrs(attrs, _allowed_attributes), do: attrs

  @spec safe_attribute?(atom() | binary(), any(), nil | [atom()]) :: boolean()
  defp safe_attribute?(key, value, allowed_attributes) do
    name = to_string(key)

    not String.starts_with?(name, "on") and
      Attributes.safe_uri?(key, value) and
      case allowed_attributes do
        nil -> true
        list -> key in list or name in list
      end
  end

  # `handle_finalize/1` is one of the `defoverridable` helpers generated by
  # `use Md.Listener`; the only behaviour callback is `element/2`.
  def handle_finalize(%State{ast: ast} = state) do
    {:update, %{state | ast: sanitize(ast)}}
  end

  def handle_finalize(_state), do: :ok
end
